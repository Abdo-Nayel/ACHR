class PaymentReminderRuleViewSet(TenantModelViewSet):
    """Dunning rules.

    Guarded by the ``sales.invoice`` permissions rather than a resource of its
    own: ``config/permissions.json`` has no ``reminder_rule`` resource, and a
    codename invented here would be one nobody can ever hold, because
    ``HasPermission`` denies anything absent from the catalogue. Writing a
    dunning rule is in practice the same authority as sending an invoice.
    """

    permission_domain = "sales"
    resource = "invoice"
    scope_resource = "invoice"
    queryset = PaymentReminderRule.objects.all()
    serializer_class = PaymentReminderRuleSerializer
    pagination_class = SmallPagePagination
    filterset_fields = ("is_active", "channel", "notify_internal_only")
    search_fields = ("name", "template_subject")
    ordering_fields = ("offset_days", "name")
    ordering = ("offset_days",)
    extra_permissions = {
        "create": ["sales.invoice.send"],
        "update": ["sales.invoice.send"],
        "partial_update": ["sales.invoice.send"],
    }

    def get_queryset(self):
        # ``PaymentReminderRule`` is configuration, not a scoped document: the
        # ABAC scope for ``invoice`` filters on ``created_by``/``project``,
        # columns this model does not have. Bypassing the scope narrowing (but
        # not the tenant manager) is deliberate and confined to this class.
        queryset = PaymentReminderRule.objects.all()
        if self.ordering:
            queryset = queryset.order_by(*self.ordering)
        return queryset


