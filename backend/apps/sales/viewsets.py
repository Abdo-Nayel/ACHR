class InvoiceViewSet(IdempotentActionMixin, TenantModelViewSet):
    """Customer invoices and the five moves they can make.

    Lines are editable only while the invoice is DRAFT — enforced on
    :class:`~apps.sales.serializers.InvoiceSerializer`, which turns the nested
    ``lines`` field read-only once the status leaves DRAFT. After issue the
    document has been sent to a customer and posted to the ledger; the
    corrections are a credit note (reduce what is owed) or a write-off
    (recognise it will not be collected), never an edit.
    """

    permission_domain = "sales"
    resource = "invoice"
    queryset = Invoice.objects.all()
    serializer_class = InvoiceSerializer
    select_related = ("customer", "journal_entry", "project")
    prefetch_related = ("lines", "lines__tax_rate")
    filterset_fields = (
        "status", "customer", "currency", "project", "issue_date", "due_date",
    )
    search_fields = ("number", "order_number", "subject", "customer__name", "customer__code", "notes")
    ordering_fields = ("issue_date", "due_date", "number", "total_amount", "amount_due")
    ordering = ("-issue_date", "-number")
    extra_permissions = {
        "attachments": ["sales.invoice.update"],
        "issue": ["sales.invoice.issue"],
        "void": ["sales.invoice.void"],
        "write_off": ["sales.invoice.write_off"],
        "send_reminder": ["sales.invoice.send"],
        "pdf": ["sales.invoice.read"],
        "journal_entry": ["sales.invoice.read", "accounting.journal_entry.read"],
    }

    @action(detail=True, methods=["get", "post"], url_path="attachments",
            parser_classes=[MultiPartParser, FormParser])
    def attachments(self, request, pk=None):
        """``GET`` lists this invoice's files; ``POST`` uploads one.

        Multipart, one file per request. Not a JSON body with base64: a 10 MB
        PDF becomes 13 MB of base64 that has to be held in memory as a string
        on both sides, and every proxy in between logs the request body.

        The hash is computed by streaming the upload in chunks rather than
        calling ``.read()`` — Django spools anything over
        ``FILE_UPLOAD_MAX_MEMORY_SIZE`` to a temp file precisely so it never
        has to be resident, and reading it whole gives that back.

        Allowed while the invoice is issued, unlike editing it. An attachment
        does not change what the invoice *says* — the signed delivery note
        usually arrives after the invoice has gone out, and refusing it would
        mean the evidence lives in somebody's inbox instead.
        """
        import hashlib  # noqa: PLC0415

        invoice = self.get_object()

        if request.method == "GET":
            rows = InvoiceAttachment.objects.filter(invoice=invoice)
            return Response(
                InvoiceAttachmentSerializer(
                    rows, many=True, context=self.get_serializer_context()
                ).data
            )

        body = InvoiceAttachmentUploadSerializer(data=request.data)
        body.is_valid(raise_exception=True)
        upload = body.validated_data["file"]

        digest = hashlib.sha256()
        for chunk in upload.chunks():
            digest.update(chunk)
        sha256 = digest.hexdigest()
        upload.seek(0)

        # Checked here for a readable message; `uq_invoice_attachment_sha256`
        # is what actually guarantees it against two concurrent uploads.
        if InvoiceAttachment.objects.filter(
            invoice=invoice, sha256=sha256
        ).exists():
            raise DomainError(
                f"{upload.name} is already attached to this invoice. "
                f"Attaching the same file twice is almost always a repeated "
                f"click rather than a second document."
            )

        attachment = InvoiceAttachment(
            tenant_id=invoice.tenant_id,
            invoice=invoice,
            original_filename=(upload.name or "file")[:255],
            content_type=(upload.content_type or "").split(";")[0].strip()[:100],
            size_bytes=upload.size,
            sha256=sha256,
            description=body.validated_data.get("description", ""),
            uploaded_by_id=getattr(request.user, "id", None),
            created_by_id=getattr(request.user, "id", None),
        )
        # Assigned after construction so `invoice_attachment_path` can read
        # tenant_id and invoice_id off the instance to build the key.
        attachment.file = upload
        attachment.save()

        return Response(
            InvoiceAttachmentSerializer(
                attachment, context=self.get_serializer_context()
            ).data,
            status=status.HTTP_201_CREATED,
        )


    # -- generated transitions ---------------------------------------------
    # ``url_path`` is passed explicitly on every one of these: without it the
    # generated handler is named ``transition`` and DRF would mount all three
    # at the same URL.

    issue = transition_action(
        "apps.sales.services.invoice_workflow.issue_invoice",
        url_path="issue",
    )

    void = transition_action(
        "apps.sales.services.invoice_workflow.void_invoice",
        url_path="void",
        body_serializer=ReasonRequiredTransitionSerializer,
        pass_reason=True,
    )

    write_off = transition_action(
        "apps.sales.services.invoice_workflow.write_off_invoice",
        url_path="write-off",
        body_serializer=WriteOffInputSerializer,
        pass_reason=True,
        build_kwargs=lambda view, instance, payload: {
            "write_off_date": payload.get("write_off_date")
        },
    )

    # -- hand-written actions ----------------------------------------------

    @action(detail=True, methods=["post"], url_path="send-reminder")
    def send_reminder(self, request, pk=None):
        """Queue a dunning reminder for this invoice.

        Writes a :class:`~apps.sales.models.PaymentReminderLog` row in PENDING
        and returns 202; it does not send anything inline. Sending inside the
        request would mean an SMTP or SMS provider's latency is the user's
        latency, and a provider timeout would leave the caller unable to tell
        whether the customer was contacted — so they would click again, and the
        customer would be chased twice for the same invoice.

        The log row is written *before* dispatch for the same reason the
        webhook receiver stores before processing: a crash between "sent" and
        "recorded" produces a duplicate on the next run, and a customer chased
        twice in one day is a complaint. ``(invoice, rule, scheduled_for)`` is
        the dedup key, which is why extending a due date legitimately allows
        the same rule to fire again.

        Refused for invoices with nothing outstanding. Chasing a paid invoice
        is the single fastest way to make a tenant distrust the whole module.
        """
        invoice = self.get_object()
        body = SendReminderInputSerializer(data=request.data)
        body.is_valid(raise_exception=True)

        if invoice.status not in OPEN_INVOICE_STATUSES:
            raise DomainError(
                f"Invoice {invoice.number or invoice.id} is "
                f"{invoice.get_status_display().lower()} and has nothing "
                f"outstanding to chase."
            )

        rule_id = body.validated_data.get("rule")
        rules = PaymentReminderRule.objects.filter(is_active=True)
        rule = rules.filter(pk=rule_id).first() if rule_id else rules.order_by(
            "offset_days"
        ).first()
        if rule is None:
            raise DomainError(
                "No active payment reminder rule is configured. Create one "
                "before sending reminders, so the wording and the channel are a "
                "tenant decision rather than a hard-coded default."
            )

        if (invoice.amount_due or ZERO) < (rule.minimum_amount_due or ZERO):
            raise DomainError(
                f"Invoice {invoice.number} owes {invoice.amount_due} "
                f"{invoice.currency}, below rule '{rule.name}'s minimum of "
                f"{rule.minimum_amount_due}. Chasing it costs more than it "
                f"collects."
            )

        from datetime import timedelta

        scheduled_for = invoice.due_date + timedelta(days=rule.offset_days)

        def run(_key: Optional[str]) -> PaymentReminderLog:
            log, created = PaymentReminderLog.objects.get_or_create(
                invoice=invoice,
                rule=rule,
                scheduled_for=scheduled_for,
                defaults={
                    "tenant_id": invoice.tenant_id,
                    "channel": rule.channel,
                    "recipient": invoice.customer.email,
                    "status": PaymentReminderLog.Status.PENDING,
                    "amount_due_snapshot": invoice.amount_due,
                    "created_by_id": getattr(request.user, "id", None),
                },
            )
            if not created:
                logger.info(
                    "reminder already logged for invoice=%s rule=%s scheduled=%s",
                    invoice.id, rule.id, scheduled_for,
                )
            return log

        result = run(None)
        return Response(
            {
                "id": str(result.id),
                "invoice": str(invoice.id),
                "rule": str(rule.id),
                "channel": result.channel,
                "recipient": result.recipient,
                "scheduled_for": result.scheduled_for.isoformat(),
                "status": result.status,
                "detail": (
                    "Reminder queued. Delivery is asynchronous; poll the "
                    "reminder log for the outcome."
                ),
            },
            status=status.HTTP_202_ACCEPTED,
        )

    @action(detail=True, methods=["get"], url_path="pdf")
    def pdf(self, request, pk=None):
        """``GET /invoices/{id}/pdf`` — **not implemented**.

        Mounted so the route exists in the schema and the frontend can be built
        against it. A real implementation renders from a *stored* snapshot of
        the invoice as issued, not from the live rows: an invoice PDF is the
        document the customer received, and re-rendering it from current data
        silently produces a different document if anything downstream changed —
        a renamed customer, a re-coded account, a corrected tax rate. The
        rendered bytes are then stored and served, so the same request always
        returns the same file.
        """
        self.get_object()
        raise NotImplementedYet(
            "Invoice PDF rendering is not implemented yet. It must render from "
            "a stored snapshot of the invoice as issued and cache the result, "
            "so that re-fetching the PDF of a historical invoice cannot return "
            "a document different from the one the customer received."
        )

    @action(detail=True, methods=["get"], url_path="journal-entry")
    def journal_entry(self, request, pk=None):
        """The journal entry this invoice posted when it was issued.

        The link the auditor follows from a document to its ledger effect. A
        draft invoice has none — that is not an error, it is the definition of
        a draft — so it answers 404 with a message saying so rather than an
        empty body the client has to guess at.
        """
        from rest_framework.exceptions import NotFound

        from apps.accounting.serializers import JournalEntrySerializer

        invoice = self.get_object()
        if invoice.journal_entry_id is None:
            raise NotFound(
                f"Invoice {invoice.number or invoice.id} has not been issued, so "
                f"it has no journal entry. Nothing is posted to the ledger until "
                f"POST /invoices/{{id}}/issue succeeds."
            )
        return Response(
            JournalEntrySerializer(
                invoice.journal_entry, context=self.get_serializer_context()
            ).data
        )


