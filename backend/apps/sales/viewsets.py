logger = logging.getLogger(__name__)

#: Invoice states that still contribute to the AR control account.
OPEN_INVOICE_STATUSES = (
    Invoice.Status.SENT,
    Invoice.Status.PARTIALLY_PAID,
    Invoice.Status.OVERDUE,
)


class WriteOffInputSerializer(ReasonRequiredTransitionSerializer):
    """Body for ``POST /invoices/{id}/write-off``.

    ``write_off_date`` is separate from the invoice's own dates because a bad
    debt is recognised when it is *decided*, not when the invoice was raised.
    Defaulting it to today (in the service) rather than to the invoice date
    keeps the expense in the period the decision was taken, which is where an
    auditor expects to find it.
    """

    write_off_date = serializers.DateField(required=False, allow_null=True)


class SendReminderInputSerializer(TransitionSerializer):
    """Body for ``POST /invoices/{id}/send-reminder``."""

    rule = serializers.UUIDField(
        required=False,
        allow_null=True,
        help_text="PaymentReminderRule to use. Defaults to the oldest active rule.",
    )


