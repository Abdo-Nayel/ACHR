class CustomerViewSet(TenantModelViewSet):
    """Customer master data, statements and per-customer invoice lists."""

    permission_domain = "sales"
    resource = "customer"
    queryset = Customer.objects.all()
    serializer_class = CustomerSerializer
    select_related = ("receivable_account",)
    pagination_class = SmallPagePagination
    filterset_fields = ("is_active", "currency", "has_credit_limit")
    search_fields = ("code", "name", "display_name", "email", "tax_number")
    ordering_fields = ("name", "code", "created_at")
    ordering = ("name",)
    extra_permissions = {
        "statement": ["sales.customer.read", "sales.invoice.read"],
        "invoices": ["sales.invoice.read"],
        "archive": ["sales.customer.archive"],
    }

    def get_queryset(self):
        """Annotate the open balance so a list page is one query, not N+1.

        Filtered aggregate rather than a subquery per row: a page of 100
        customers each triggering its own ``SUM(amount_due)`` is 100 round
        trips, and it is the AR list that the credit controller reloads all
        day.
        """
        return super().get_queryset().annotate(
            outstanding_balance=Sum(
                "invoices__amount_due",
                filter=Q(invoices__status__in=OPEN_INVOICE_STATUSES),
            )
        )

    @action(detail=True, methods=["get"], url_path="statement")
    def statement(self, request, pk=None):
        """Everything this customer owes, and what it is made up of.

        The document a credit controller sends when a customer says "what is
        this balance?". Deliberately built from the invoices and credit notes
        themselves rather than from the AR control account: the control account
        knows the total, only the sub-ledger knows which documents make it up,
        and a statement that cannot be broken down is one nobody can dispute or
        agree.

        Unpaginated and bounded by a date window (default: the last 12 months)
        for the same reason the tree endpoint is unpaginated — a statement cut
        in half at an arbitrary row is not a statement.
        """
        from django.utils.dateparse import parse_date

        customer = self.get_object()
        raw_from = request.query_params.get("date_from")
        raw_to = request.query_params.get("date_to")
        date_to = parse_date(raw_to) if raw_to else timezone.localdate()
        date_from = (
            parse_date(raw_from)
            if raw_from
            else date_to.replace(year=date_to.year - 1)
        )

        invoices = (
            Invoice.objects.filter(
                customer=customer, issue_date__gte=date_from, issue_date__lte=date_to
            )
            .exclude(status=Invoice.Status.DRAFT)
            .order_by("issue_date", "number")
        )
        credit_notes = (
            CreditNote.objects.filter(
                customer=customer, issue_date__gte=date_from, issue_date__lte=date_to
            )
            .exclude(status=CreditNote.Status.DRAFT)
            .order_by("issue_date", "number")
        )

        rows: list[dict[str, Any]] = []
        for invoice in invoices:
            rows.append(
                {
                    "type": "invoice",
                    "id": str(invoice.id),
                    "number": invoice.number,
                    "date": invoice.issue_date.isoformat(),
                    "due_date": invoice.due_date.isoformat(),
                    "currency": invoice.currency,
                    "status": invoice.status,
                    "total_amount": f"{invoice.total_amount:f}",
                    "amount_paid": f"{invoice.amount_paid:f}",
                    "amount_due": f"{invoice.amount_due:f}",
                }
            )
        for note in credit_notes:
            rows.append(
                {
                    "type": "credit_note",
                    "id": str(note.id),
                    "number": note.number,
                    "date": note.issue_date.isoformat(),
                    "currency": note.currency,
                    "status": note.status,
                    "total_amount": f"{-note.total_amount:f}",
                    "amount_remaining": f"{note.amount_remaining:f}",
                }
            )
        rows.sort(key=lambda row: (row["date"], row.get("number") or ""))

        outstanding = Invoice.objects.filter(
            customer=customer, status__in=OPEN_INVOICE_STATUSES
        ).aggregate(total=Sum("amount_due"))["total"] or ZERO
        unapplied_credit = CreditNote.objects.filter(
            customer=customer, status__in=[CreditNote.Status.ISSUED]
        ).aggregate(total=Sum("amount_remaining"))["total"] or ZERO

        return Response(
            {
                "customer": {
                    "id": str(customer.id),
                    "code": customer.code,
                    "name": customer.name,
                    "currency": customer.currency,
                },
                "period": {"from": date_from.isoformat(), "to": date_to.isoformat()},
                "lines": rows,
                "outstanding_balance": f"{outstanding:f}",
                "unapplied_credit": f"{unapplied_credit:f}",
                "net_balance": f"{outstanding - unapplied_credit:f}",
                "as_of": timezone.now().isoformat(),
            }
        )

    @action(detail=True, methods=["get"], url_path="invoices")
    def invoices(self, request, pk=None):
        """This customer's invoices, paginated with the standard cursor.

        A filtered ``/invoices/?customer=<id>`` would serve the same rows, but
        the nested route is what the customer detail screen calls and it keeps
        the ABAC scope of *both* resources in play: the customer must be
        visible to the caller, and the invoices are then narrowed again by the
        invoice scope.
        """
        customer = self.get_object()
        queryset = (
            Invoice.objects.filter(customer=customer)
            .select_related("customer", "journal_entry")
            .order_by("-issue_date", "-number")
        )
        status_filter = request.query_params.getlist("status")
        if status_filter:
            queryset = queryset.filter(status__in=status_filter)
        if request.query_params.get("open_only") == "true":
            queryset = queryset.filter(status__in=OPEN_INVOICE_STATUSES)

        page = self.paginate_queryset(queryset)
        context = self.get_serializer_context()
        if page is not None:
            return self.get_paginated_response(
                InvoiceSerializer(page, many=True, context=context).data
            )
        return Response(InvoiceSerializer(queryset, many=True, context=context).data)


