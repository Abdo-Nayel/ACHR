class InvoiceAttachmentViewSet(TenantModelViewSet):
    """Files attached to an invoice.

    Listing and deleting live here; *uploading* is an action on the invoice
    (``POST /invoices/{id}/attachments/``), because the file only means
    anything in the context of the document it belongs to and a top-level
    create would need the invoice id in the body anyway.

    Permissioned as ``sales.invoice.update``: attaching or removing evidence
    changes what the invoice says, so anyone who may not edit the invoice may
    not edit its attachments either.

    Unlike most documents here, attachments **can** be hard-deleted. They are
    not financial records — nothing in the ledger references them, no total
    changes — and an evidence file uploaded in error (the wrong customer's
    contract) is a document that must actually go, not one that lingers
    archived. The invoice's own immutability is untouched.
    """

    permission_domain = "sales"
    resource = "invoice"
    scope_resource = "invoice"
    queryset = InvoiceAttachment.objects.all()
    serializer_class = InvoiceAttachmentSerializer
    select_related = ("invoice", "uploaded_by")
    pagination_class = SmallPagePagination
    filterset_fields = ("invoice",)
    ordering_fields = ("created_at", "size_bytes")
    ordering = ("-created_at",)
    extra_permissions = {
        "DELETE": ["sales.invoice.update"],
        "PATCH": ["sales.invoice.update"],
    }

    def destroy(self, request, *args, **kwargs):
        """Remove the row *and* the bytes.

        ``TenantModelViewSet.destroy`` refuses on principle, so this overrides
        it deliberately — see the class docstring for why an attachment is not
        a financial record. The stored file is deleted after the row so that a
        failure leaves an orphaned blob (recoverable, costs storage) rather
        than a row pointing at bytes that are gone (a broken download nobody
        can explain).
        """
        attachment = self.get_object()
        stored = attachment.file
        attachment.delete()
        try:
            stored.delete(save=False)
        except Exception:  # noqa: BLE001 - the row is already gone
            logger.warning(
                "attachment row deleted but its file could not be removed: %s",
                stored.name, exc_info=True,
            )
        return Response(status=status.HTTP_204_NO_CONTENT)
